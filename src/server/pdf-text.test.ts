import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { eq } from "drizzle-orm";
import { describe, expect, it, vi } from "vitest";

await vi.hoisted(async () => {
  const [{ mkdtemp }, { tmpdir }, { join }] = await Promise.all([import("node:fs/promises"), import("node:os"), import("node:path")]);
  process.env.STORAGE_DRIVER = "local";
  process.env.LOCAL_STORAGE_DIR = await mkdtemp(join(tmpdir(), "candid-pdftext-"));
  process.env.TOKEN_ENCRYPTION_KEY ||= "test-key";
});

import { db } from "@/db";
import { documents } from "@/db/schema";
import { makeCtx } from "../../test/factory";
import type { Ctx } from "./context";
import { createUpload, finalizeUpload, setDocumentRemoved } from "./documents";
import { extractPdfText, normalizeText } from "./pdf-text";
import { createProject } from "./projects";
import { search } from "./search";
import { localPut, verifyLocalToken } from "./storage";

// Generated by test/fixtures/make-czech-pdf.py: two pages of Czech text in an embedded font.
const CZECH_PDF = new Uint8Array(await readFile(resolve(__dirname, "../../test/fixtures/czech.pdf")));

async function upload(ctx: Ctx, name: string, bytes: Uint8Array, opts: { projectId?: string; replaceId?: string } = {}) {
  const { uploadId, upload } = await createUpload(ctx, { name, mimeType: "application/pdf", size: bytes.length, ...opts });
  await localPut(verifyLocalToken(new URL(upload.url, "http://x").searchParams.get("token"))!.key, bytes);
  return finalizeUpload(ctx, uploadId, { replaceId: opts.replaceId });
}
const row = async (id: string) => (await db.select().from(documents).where(eq(documents.id, id)))[0];

describe("PDF text extraction", () => {
  it("extracts Czech text from every page with normalized whitespace", async () => {
    const text = await extractPdfText(CZECH_PDF);
    expect(text).toContain("Přihláška do výběrového řízení");
    expect(text).toContain("Žluťoučký kůň úpěl ďábelské ódy.");
    expect(text).toContain("Smlouva o dílo: Stavební úpravy střechy, Brno"); // page 2
    expect(text).not.toMatch(/\s{2,}|^\s|\s$|\n/);
  });

  it("caps the length and rejects bytes that are not a PDF", async () => {
    expect((await extractPdfText(CZECH_PDF, { maxChars: 12 })).length).toBeLessThanOrEqual(12);
    await expect(extractPdfText(new TextEncoder().encode("%PDF-1.7\n1 0 obj\n"))).rejects.toThrow();
  });

  it("normalizes whitespace", () => {
    expect(normalizeText("  a\n\n b\t c  ")).toBe("a b c");
  });
});

describe("PDF text on upload", () => {
  it("stores the text at finalize and finds the PDF by its content, accent-insensitively, with a snippet", async () => {
    const ctx = await makeCtx();
    const p = await createProject(ctx, { name: "Výběrko" });
    const doc = await upload(ctx, "scan-001.pdf", CZECH_PDF, { projectId: p.id });
    const r = await row(doc.id);
    expect(r.contentText).toContain("Přihláška");
    expect(r.textExtractedAt).toBeInstanceOf(Date);
    expect(doc).not.toHaveProperty("contentText"); // never sent to the browser with the document

    const res = await search(ctx, "prihlaska");
    expect(res.documents).toHaveLength(1);
    expect(res.documents[0]).toMatchObject({ id: doc.id, projectId: p.id, projectName: "Výběrko" });
    expect(res.documents[0].snippet?.text).toContain("Přihláška");
    expect((await search(ctx, "STRECHY brno")).documents.map((d) => d.id)).toEqual([doc.id]);
    expect((await search(ctx, "strechy praha")).documents).toEqual([]); // every word must match

    await setDocumentRemoved(ctx, doc.id, true);
    expect((await search(ctx, "prihlaska")).documents).toEqual([]);
  });

  it("never fails the upload when the PDF cannot be read", async () => {
    const ctx = await makeCtx();
    const doc = await upload(ctx, "broken.pdf", new TextEncoder().encode("%PDF-1.7\n1 0 obj\n garbage"));
    const r = await row(doc.id);
    expect(r.uploadedAt).toBeInstanceOf(Date);
    expect(r.contentText).toBeNull();
    expect(r.textExtractedAt).toBeInstanceOf(Date); // marked done: the backfill does not retry it
  });

  it("replacing a file replaces its text", async () => {
    const ctx = await makeCtx();
    const doc = await upload(ctx, "v1.pdf", CZECH_PDF);
    await upload(ctx, "v2.pdf", new TextEncoder().encode("%PDF-1.7\n1 0 obj\n"), { replaceId: doc.id });
    expect((await row(doc.id)).contentText).toBeNull();
    expect((await search(ctx, "prihlaska")).documents).toEqual([]);
  });

  it("does not leak PDF text across workspaces", async () => {
    const a = await makeCtx();
    const b = await makeCtx();
    await upload(a, "tajne.pdf", CZECH_PDF);
    expect((await search(b, "prihlaska")).documents).toEqual([]);
  });
});
